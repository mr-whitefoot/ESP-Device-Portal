#pragma once
#include <ArduinoJson.h>

// Контракт между ядром и конечным устройством.
//
// Связывание на этапе компиляции: ядро зовёт эти функции напрямую, линкер
// разрешает символы. Виртуальных методов нет намеренно -- устройство в
// прошивке одно, подменять его в рантайме незачем, а vtable стоила бы флеша.
// Новое устройство = новый каталог lib/device_*, реализующий эти функции.
//
// Функции про UI неизбежно пахнут GyverPortal, и это осознанный размен:
// блок устройства на странице по-настоящему зависит от того, чем рисуют.
// Если появится второй способ управления (свой протокол), он будет опираться
// на fillState/onCommand, а не на buildHomeUi.
//
// Ядро, в свою очередь, предоставляет устройству:
//   println(text)      -- лог в Serial и в портал
//   publishState()     -- опубликовать состояние в MQTT прямо сейчас
//   restart()          -- завершение работы и перезагрузка ESP
//   portal, form       -- объекты GyverPortal для разбора своих форм
//   settings::*        -- слой настроек

namespace device {

// --- Описание -------------------------------------------------------------

// Модель для карточки устройства в HomeAssistant, например "Relay".
const char* model();

// Компонент HomeAssistant: "switch", "sensor", "binary_sensor".
// Попадает в discovery-топик, поэтому только [a-zA-Z0-9_-].
const char* haComponent();

// Идентификаторы динамически обновляемых полей портала через запятую,
// например "switch". Пустая строка, если обновлять нечего.
const char* updateIds();

// --- Жизненный цикл -------------------------------------------------------

// Объявление своих параметров со значениями по умолчанию. Зовётся до begin().
void defineSettings();

// Инициализация железа. Настройки уже загружены.
void begin();

// Обслуживание из loop().
void tick();

// --- Портал ---------------------------------------------------------------

// Блок на главной странице.
void buildHomeUi();

// Кнопки-ссылки на свои страницы внизу главной.
void buildHomeLinks();

// Свои страницы. Вернуть true, если страница отрисована.
bool buildPage(const String& uri);

// Блок в Preferences.
void buildSettingsUi();

// Разбор своих полей формы Preferences.
void readSettingsForm();

// Свои формы. Вернуть true, если форма разобрана.
bool handleForm();

// Клики на главной странице.
void handleClick();

// Обновление динамических полей, перечисленных в updateIds().
void updateUi();

// --- MQTT -----------------------------------------------------------------

// Поля discovery, специфичные для устройства: cmd_t, val_tpl, dev_cla,
// единицы измерения. Общая часть (имя, топики, карточка device) -- на ядре.
void fillDiscovery(JsonDocument& doc);

// Полезная нагрузка состояния.
void fillState(JsonDocument& doc);

// Команда из командного топика. У датчика пустая.
void onCommand(const String& payload);

}  // namespace device
