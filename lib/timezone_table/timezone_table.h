#pragma once
#include <stdint.h>

// Таблица часовых поясов -- единственный источник правды.
// Индекс записи это ровно то значение, которое отдаёт GP.SELECT на странице
// Preferences, поэтому подпись и смещение обязаны лежать рядом: раньше список
// подписей жил в webface.h, а смещения отдельной цепочкой if-ов, и они разошлись.
//
// Заголовок намеренно не зависит от Arduino, чтобы собираться в native-тестах.

struct TimezoneEntry {
  const char* label;
  int16_t offsetMinutes;
};

static const TimezoneEntry TIMEZONES[] = {
    {"-12:00", -720}, {"-11:00", -660}, {"-10:00", -600}, {"-09:30", -570},
    {"-09:00", -540}, {"-08:00", -480}, {"-07:00", -420}, {"-06:00", -360},
    {"-05:00", -300}, {"-04:00", -240}, {"-03:30", -210}, {"-03:00", -180},
    {"-02:00", -120}, {"-01:00", -60},  {"00:00", 0},     {"+01:00", 60},
    {"+02:00", 120},  {"+03:00", 180},  {"+03:30", 210},  {"+04:00", 240},
    {"+04:30", 270},  {"+05:00", 300},  {"+05:30", 330},  {"+05:45", 345},
    {"+06:00", 360},  {"+06:30", 390},  {"+07:00", 420},  {"+08:00", 480},
    {"+08:45", 525},  {"+09:00", 540},  {"+09:30", 570},  {"+10:00", 600},
    {"+10:30", 630},  {"+11:00", 660},  {"+12:00", 720},  {"+13:00", 780},
    {"+14:00", 840},
};

static const uint8_t TIMEZONE_COUNT = sizeof(TIMEZONES) / sizeof(TIMEZONES[0]);

// Индекс UTC, он же значение по умолчанию для базы.
static const uint8_t TIMEZONE_UTC = 14;

inline int tzOffsetSeconds(uint8_t index) {
  if (index >= TIMEZONE_COUNT) return 0;
  return (int)TIMEZONES[index].offsetMinutes * 60;
}
